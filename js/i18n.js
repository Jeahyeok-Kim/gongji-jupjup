  function formatWon(won, lang) {
    if (typeof won !== 'number' || !isFinite(won)) return '';
    const man = won / 10000;
    const manText = Number.isInteger(man) ? man.toLocaleString('en-US') : null;
    if (lang === 'en') return '₩' + won.toLocaleString('en-US');
    if (lang === 'zh') return manText && won >= 10000 ? `${manText}万韩元` : `${won.toLocaleString('en-US')}韩元`;
    if (lang === 'ja') return manText && won >= 10000 ? `${manText}万ウォン` : `${won.toLocaleString('en-US')}ウォン`;
    return manText && won >= 10000 ? `${manText}만 원` : `${won.toLocaleString('en-US')}원`;
  }

